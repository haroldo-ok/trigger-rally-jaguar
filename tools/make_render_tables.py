"""Q15 render-only trigonometry, matching the engine's 512 angular phases."""
from pathlib import Path
import math
R=Path(__file__).resolve().parents[1]
v=[round(math.sin(i*2*math.pi/512)*32767) for i in range(512)]
(R/'src/render_tables.h').write_text('/* Generated by tools/make_render_tables.py; render only, never physics. */\nstatic const int16_t render_sine[512]={\n'+''.join('    '+','.join(map(str,v[i:i+16]))+',\n' for i in range(0,512,16))+'};\n')
