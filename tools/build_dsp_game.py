"""Compile the unchanged native game/physics equations to actual Jaguar DSP code.

The 68000 remains the real cartridge bootstrap host; GPU retains 42Bastian's
engine. No host gameplay, emulation-speed setting, or target RAM patching.
"""
from pathlib import Path
import argparse,json,re,subprocess
R=Path(__file__).resolve().parents[1];B=R/'.cache/jrisc/bin'
def run(cmd):
    print('+',' '.join(map(str,cmd)),flush=True)
    subprocess.run(list(map(str,cmd)),cwd=R,check=True)
def build(kernel=None,output=None,main_source=None,work_dir=None,header_path=None):
    W=Path(work_dir) if work_dir else R/'artifacts/dsp';W.mkdir(parents=True,exist_ok=True)
    objects=[]
    sources=[(str(main_source) if main_source else 'src/main.c',['-binary32','-dspmain']),('src/physics.c',['-binary32','-dspmain'])] if kernel is None else [(str(kernel),['-binary32','-dspmain'])]
    sources += [('src/render_math.c',['-dspmain']),('src/dsp/float32.c',['-dsplocal'])]
    for path,flags in sources:
        p=Path(path);base=W/p.stem;asm=base.with_suffix('.asm');scheduled=base.with_suffix('.s');obj=base.with_suffix('.o')
        run([B/'vbccjrisc','-quiet','-c99',('-O=1023' if p.name=='float32.c' else '-O=-1'),'-inline-depth=2','-I'+str(R/'src/dsp/include'),'-I'+str(R/'src'),'-I'+str(R/'assets'),*flags,path,'-o='+str(asm)])
        run([B/'vscjrisc','-quiet',asm,scheduled])
        run([B/'vasmjagrisc_std','-Fvobj','-quiet','-opt-jr=r28',scheduled,'-o',obj]);objects.append(obj)
    for name in ['start','data','float_fast','integers']:
        obj=W/(name+'.o');run([B/'vasmjagrisc_std','-Fvobj','-quiet','-opt-jr=r28',R/f'src/dsp/{name}.s','-o',obj]);objects.append(obj)
    target=Path(output) if output else R/'assets/dsp_game.bin';m=W/'game.map'
    run([B/'vlink','-m','-M'+str(m),'-brawbin','-x','-minalign','1','-nowarn=156','-Bstatic','-Cvbcc','-nostdlib','-T'+str(R/'src/dsp/link.ld'),*objects,'-o',target])
    text=m.read_text();symbols={}
    for line in text.splitlines():
        if '_dsp_' not in line:continue
        match=re.search(r'0x([0-9a-fA-F]+)\s+(_dsp_\w+):',line)
        if match:symbols[match[2]]=int(match[1],16)
    required=['_dsp_local_load','_dsp_local_bytes','_dsp_bss_start','_dsp_bss_end']
    if not all(k in symbols for k in required):
        print(text[-6000:]);raise RuntimeError('DSP map symbol parser needs the linker symbol format')
    assert symbols.get('_dsp_entry')==0xf1b100,'DSP entry vector placement changed'
    assert symbols['_dsp_bss_end']<0x3e000,'DSP code/data/stack overlap terrain'
    assert symbols['_dsp_local_bytes']<=0x1d00,'DSP code overlaps its real local stacks'
    payload=target.read_bytes();payload+=b'\0'*((-len(payload))%4);target.write_bytes(payload)
    header='/* Generated by tools/build_dsp_game.py. */\n#ifndef TR_DSP_IMAGE_H\n#define TR_DSP_IMAGE_H\n'+f'#define DSP_IMAGE_BYTES {len(payload)}u\n'+f'#define DSP_LOCAL_LOAD 0x{symbols["_dsp_local_load"]:x}u\n'+f'#define DSP_LOCAL_BYTES {symbols["_dsp_local_bytes"]}u\n#endif\n'
    (Path(header_path) if header_path else R/'src/dsp/image.h').write_text(header)
    (W/'layout.json').write_text(json.dumps({'image_bytes':len(payload),'symbols':symbols},indent=2)+'\n')
    return target
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--kernel',type=Path);p.add_argument('--output',type=Path);a=p.parse_args();print(build(a.kernel,a.output))
